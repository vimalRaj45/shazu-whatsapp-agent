const path = require('path');
const fs = require('fs');

const app = express();
app.use(express.json());

const PORT = process.env.PORT || 3001;
const PYTHON_WEBHOOK_URL = process.env.PYTHON_WEBHOOK_URL || 'http://127.0.0.1:5005/webhook';
const AUTH_DIR = path.join(__dirname, 'auth_info');

let sock = null;
let currentQR = null;
let connectionStatus = 'initializing'; // initializing | qr_ready | connected | reconnecting
let connectedUser = null;

// In-memory circular log buffer (last 100 events)
const activityLogs = [];
function addLog(type, message, details = null) {
  const timestamp = new Date().toLocaleTimeString('en-US', { hour12: false });
  const entry = {
    id: Date.now() + Math.random().toString(36).substr(2, 4),
    time: timestamp,
    type,
    message,
    details
  };
  activityLogs.push(entry);
  if (activityLogs.length > 100) activityLogs.shift();

  const prefix = `[${timestamp}] [${type}]`;
  console.log(`${prefix} ${message}`);
}

// Track IDs of messages sent by this bot so we NEVER reply to our own messages
const botSentMessageIds = new Set();
// Track recently processed message IDs to prevent duplicates
const processedMessageIds = new Set();

async function connectToWhatsApp() {
  addLog('SYSTEM', 'Initializing WhatsApp Multi-Device session from ' + AUTH_DIR);
  
  if (!fs.existsSync(AUTH_DIR)) {
    fs.mkdirSync(AUTH_DIR, { recursive: true });
  }

  const { state, saveCreds } = await useMultiFileAuthState(AUTH_DIR);
  const { version, isLatest } = await fetchLatestBaileysVersion();
  addLog('SYSTEM', `Using Baileys WA version v${version.join('.')}, isLatest: ${isLatest}`);

  sock = makeWASocket({
    version,
    auth: state,
    logger: pino({ level: 'silent' }),
    printQRInTerminal: false,
    generateHighQualityLinkPreview: true,
    browser: ['Shazu Soft Technologies', 'Chrome', '124.0.0']
  });

  sock.ev.on('creds.update', saveCreds);

  sock.ev.on('connection.update', async (update) => {
    const { connection, lastDisconnect, qr } = update;

    if (qr) {
      currentQR = qr;
      connectionStatus = 'qr_ready';
      addLog('QR', 'New QR Code generated. Scan in browser at http://localhost:3001/qr');
      console.log('\n======================================================');
      console.log('>>> SCAN THIS QR CODE IN WHATSAPP (Linked Devices) <<<');
      console.log('======================================================\n');
      qrcodeTerminal.generate(qr, { small: true });
      console.log('\nAlternatively, view QR code in browser at: http://localhost:3001/qr\n');
    }

    if (connection === 'close') {
      const statusCode = lastDisconnect?.error?.output?.statusCode;
      const shouldReconnect = statusCode !== DisconnectReason.loggedOut;
      connectionStatus = shouldReconnect ? 'reconnecting' : 'logged_out';
      addLog('CONN', `Connection closed (code: ${statusCode || 'unknown'}). Reconnecting: ${shouldReconnect}`);

      if (shouldReconnect) {
        setTimeout(connectToWhatsApp, 3000);
      } else {
        addLog('CONN', 'Session logged out. Clearing credentials...');
        currentQR = null;
        connectedUser = null;
        fs.rmSync(AUTH_DIR, { recursive: true, force: true });
        setTimeout(connectToWhatsApp, 2000);
      }
    } else if (connection === 'open') {
      connectionStatus = 'connected';
      currentQR = null;
      connectedUser = sock.user;
      addLog('CONN', `SUCCESS! WhatsApp Connected as: ${sock.user?.id || 'Connected'}`);
    }
  });

  // Handle incoming messages
  sock.ev.on('messages.upsert', async ({ messages, type }) => {
    if (!messages || !messages.length) return;

    for (const msg of messages) {
      const msgId = msg.key?.id;
      if (!msgId) continue;

      // 1. Ignore if already processed or if generated by this bot
      if (processedMessageIds.has(msgId) || botSentMessageIds.has(msgId)) {
        continue;
      }
      processedMessageIds.add(msgId);
      if (processedMessageIds.size > 2000) {
        const first = processedMessageIds.values().next().value;
        processedMessageIds.delete(first);
      }

      const remoteJid = msg.key?.remoteJid || '';
      // Ignore broadcast status updates, channels, and group chats
      if (
        remoteJid === 'status@broadcast' || 
        remoteJid.endsWith('@g.us') || 
        remoteJid.endsWith('@newsletter') || 
        remoteJid.includes('@broadcast')
      ) {
        continue;
      }

      // 2. Extract message text
      const messageText = 
        msg.message?.conversation || 
        msg.message?.extendedTextMessage?.text || 
        msg.message?.imageMessage?.caption || 
        msg.message?.videoMessage?.caption || 
        '';

      if (!messageText || !messageText.trim()) {
        continue;
      }

      const cleanText = messageText.trim();
      const isFromMe = Boolean(msg.key?.fromMe);
      const myId = sock.user?.id ? sock.user.id.split(':')[0] : '';
      const isSelfChat = remoteJid.includes(myId) || (sock.user?.lid && remoteJid === sock.user.lid);

      if (isFromMe) {
        if (isSelfChat) {
          // Self-Test Mode: User messaged themselves on the connected phone!
          addLog('SELF-TEST', `Detected self-test from phone owner: "${cleanText}"`);
          forwardToPythonAndReply(remoteJid, myId, 'Phone Owner (Self-Test)', cleanText);
        } else {
          // Human owner sent message to an external client
          addLog('HUMAN', `Owner replied to ${remoteJid}. AI will not interfere.`);
        }
        continue;
      }

      // Normal Inbound Customer Message
      const senderPhone = remoteJid.replace(/[^0-9]/g, '');
      const senderName = msg.pushName || 'Prospective Client';
      addLog('INBOUND', `From ${senderPhone} (${senderName}): "${cleanText}"`);

      forwardToPythonAndReply(remoteJid, senderPhone, senderName, cleanText);
    }
  });
}

// Forward message to Python AI Engine and send reply via WhatsApp
function forwardToPythonAndReply(jid, phone, name, text) {
  const payload = JSON.stringify({
    phone: phone,
    name: name,
    message: text
  });

  const url = new URL(PYTHON_WEBHOOK_URL);
  const options = {
    hostname: url.hostname,
    port: url.port,
    path: url.pathname,
    method: 'POST',
    headers: {
      'Content-Type': 'application/json',
      'Content-Length': Buffer.byteLength(payload),
      'Connection': 'close'
    }
  };

  const req = http.request(options, (res) => {
    let responseData = '';
    res.on('data', (chunk) => { responseData += chunk; });
    res.on('end', async () => {
      try {
        if (res.statusCode !== 200) {
          addLog('ERROR', `Python engine returned HTTP ${res.statusCode}: ${responseData.substring(0, 120)}`);
          return;
        }
        const json = JSON.parse(responseData);
        const replyText = json.reply;

        if (replyText && sock) {
          addLog('AI-REPLY', `Generated reply for ${name} (${replyText.length} chars). Sending...`);

          // 1. Simulate human typing presence
          try {
            await sock.sendPresenceUpdate('composing', jid);
          } catch (e) {}

          // 2. Short natural typing delay (2 seconds)
          await new Promise(r => setTimeout(r, 2000));

          // 3. Clear typing indicator
          try {
            await sock.sendPresenceUpdate('paused', jid);
          } catch (e) {}

          // 4. Send message
          const sent = await sock.sendMessage(jid, { text: replyText });
          if (sent?.key?.id) {
            botSentMessageIds.add(sent.key.id);
            if (botSentMessageIds.size > 2000) {
              const first = botSentMessageIds.values().next().value;
              botSentMessageIds.delete(first);
            }
          }
          addLog('DELIVERED', `Reply delivered successfully to ${phone}!`);
        } else {
          addLog('AI-WARN', `No reply returned by AI engine for ${phone}`);
        }
      } catch (err) {
        addLog('ERROR', `Failed parsing Python response: ${err.message}`);
      }
    });
  });

  req.on('error', (err) => {
    addLog('ERROR', `Failed to reach Python AI Webhook at ${PYTHON_WEBHOOK_URL}: ${err.message}`);
  });

  req.write(payload);
  req.end();
}

