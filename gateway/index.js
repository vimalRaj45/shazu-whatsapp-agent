// Endpoint to disconnect / unlink WhatsApp session
app.post('/api/disconnect', async (req, res) => {
  addLog('SYSTEM', 'Disconnect requested. Unlinking WhatsApp session...');
  try {
    if (sock) {
      try {
        await sock.logout();
      } catch (e) {}
      try {
        sock.end(new Error('User disconnected'));
      } catch (e) {}
    }
  } catch (err) {}

  connectionStatus = 'initializing';
  connectedUser = null;
  currentQR = null;

  // Clear credentials folder so next connection requests fresh QR
  try {
    if (fs.existsSync(AUTH_DIR)) {
      fs.rmSync(AUTH_DIR, { recursive: true, force: true });
    }
  } catch (err) {
    console.error('Error clearing auth dir:', err);
  }

  // Reinitialize socket to generate fresh QR code
  setTimeout(() => {
    connectToWhatsApp();
  }, 1000);

  res.json({ success: true, message: 'WhatsApp session disconnected. New QR code is generating...' });
});

